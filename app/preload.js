const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('teacher', {
  apiBase: 'http://127.0.0.1:8765',
  hitbox: (r) => ipcRenderer.send('hitbox', r),
  drag: (dx, dy) => ipcRenderer.send('teacher:drag', { dx, dy }),
  dragEnd: (w, h) => ipcRenderer.send('teacher:drag-end', { w, h }),
  edgeResize: (edge, dx, dy) => ipcRenderer.send('teacher:edge-resize', { edge, dx, dy }),
  hide: () => ipcRenderer.send('teacher:hide'),
  quit: () => ipcRenderer.send('teacher:quit'),
  openSettings: () => ipcRenderer.send('open-settings'),
  cfg: () => ipcRenderer.invoke('teacher:cfg'),
  setModel: (m) => ipcRenderer.send('teacher:set-model', m),
  setScale: (s) => ipcRenderer.send('teacher:set-scale', s),
  zoom: (d) => ipcRenderer.send('teacher:zoom', d),
  copyText: (t) => ipcRenderer.invoke('teacher:copy', t),
  zoomReset: () => ipcRenderer.send('teacher:zoom-reset'),
  onZoomPct: (cb) => ipcRenderer.on('teacher:zoom-pct', (e, p) => cb(p)),
  setBubbleW: (w) => ipcRenderer.send('teacher:set-bubblew', w),
  onWake: (cb) => ipcRenderer.on('teacher:wake', () => cb()),
  onSay: (cb) => ipcRenderer.on('teacher:say', (e, t, u) => cb(t, u)),
  dnd: () => ipcRenderer.send('teacher:dnd'),
  summon: () => ipcRenderer.send('teacher:summon'),
  // 1012v2 独立抓拍窗：打开/接收回传照片（主进程中转，抓拍窗可自由移动缩放）
  camOpen: () => ipcRenderer.send('cam:open'),
  onCam: (cb) => ipcRenderer.on('cam:result', (e, d) => cb(d)),
  startTeacherCalib: () => ipcRenderer.send('teacher:open-calib'),
  // 1003(卡通形象): 设置页保存后重载老师窗口, 形象即时生效
  reloadWin: () => ipcRenderer.send('teacher:reload-win'),
  getMode: () => ipcRenderer.invoke('teacher:mode'),
  saveText: (content, filename) => ipcRenderer.invoke('teacher:save-text', { content, filename }),
  bustData: () => ipcRenderer.invoke('teacher:bust-data'),
  onMode: (cb) => ipcRenderer.on('teacher:mode', (e, m) => cb(m)),
  settings: {
    read: () => fetch('http://127.0.0.1:8765/personality').then(r => r.json()),
    write: (p) => fetch('http://127.0.0.1:8765/personality', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(p) }).then(r => r.json()),
    health: () => fetch('http://127.0.0.1:8765/health').then(r => r.json()),
    reset: () => fetch('http://127.0.0.1:8765/reset', { method: 'POST' }).then(r => r.json()),
    calibOn: () => fetch('http://127.0.0.1:8765/calibflag', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ on: true }) }).then(r => r.json()),
  },
});
